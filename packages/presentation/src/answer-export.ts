import type { Run, Source } from '../../core/src/types';
import { estimateContent } from '../../core/src/answers';
import { analysisMarkdown } from './visual-analysis';
import { financialAnalysisMarkdown } from './financial-analysis';
import { tabularReportMarkdown } from './tabular-report';
import { postTextLabels } from '../../data-layer/src/tabular/post-presentation';
import { readablePostMarkdown } from './post-markdown';

export function latestOutputRun(run: Run | null, previous: readonly Run[]): Run | null {
  return run?.result || run?.reply ? run : previous.findLast(turn => turn.status === 'completed' && (turn.result || turn.reply)) ?? null;
}

/** Copy and download share the saved answer, never a remembered earlier report. */
export function answerDocument(run: Run, fallbackSources: readonly Source[] = [], example = false): { title: string; content: string } | null {
  const output = run.result ?? run.reply;
  if (!output) return null;
  const title = run.result?.title ?? (output.answer?.kind === 'hypothetical' ? 'Hypothetical estimate' : output.answer?.kind === 'missing-data' ? 'Data needed' : run.task.slice(0,160));
  const labels = new Map((run.sources ?? fallbackSources).map(source => [source.id,source.title]));
  const cited = (output.citations ?? []).map(id => labels.get(id) ?? 'Saved source');
  const body = output.answer?.estimate ? estimateContent(output.answer) : output.tabularAnalysis
    ? readablePostMarkdown(output.content, postTextLabels(output.tabularAnalysis.result, new Map(Object.entries(output.tabularAnalysis.postLabels ?? {})))) : output.content;
  const literal = (value: string) => value.replace(/[\r\n]+/g,' ').replace(/[\\`*_{}\[\]()<>#!|]/g,'\\$&');
  // Workspace-only links become readable source labels in a standalone file.
  const content = body.replace(/\[([^\]]+)\]\(source:([^)]+)\)/g, (_match, label: string, id: string) => literal(labels.get(id) ?? label));
  return { title, content: [
    `# ${literal(title)}`,
    ...(example ? ['> Illustrative workspace example using fictional notes. Not generated by a model run.'] : []),
    ...(run.weeklyReview ? [`Reporting dates: ${run.weeklyReview.period.from} (inclusive) to ${run.weeklyReview.period.to} (exclusive) · UTC.`,
      ...(['partial','failed'].includes(run.weeklyReview.presync.status) ? ['Some accounts could not refresh. This report uses their last saved data.'] : []),
      ...(run.weeklyReview.missingConnectionIds.length ? [`${run.weeklyReview.missingConnectionIds.length} selected accounts are missing from this review.`] : [])] : []),
    content,
    ...(output.analysis ? [analysisMarkdown(output.analysis)] : []),
    ...(output.financialAnalysis ? [financialAnalysisMarkdown(output.financialAnalysis)] : []),
    ...(output.tabularAnalysis ? [tabularReportMarkdown(output.tabularAnalysis)] : []),
    ...(output.answer?.missing?.length ? ['## Missing data', ...output.answer.missing.map(item => `- ${literal(item)}`)] : []),
    ...(output.answer?.suggestions?.length ? ['## Questions to explore', ...output.answer.suggestions.map(item => `- ${literal(item)}`)] : []),
    ...(cited.length ? ['## Sources', ...cited.map(title => `- ${literal(title)}`), 'Original evidence requires access to this workspace.'] : []),
    ...(output.answer ? [`<!-- Rivet answer: ${JSON.stringify({ id: output.answer.id, kind: output.answer.kind }).replace(/</g, '\\u003c').replace(/>/g, '\\u003e')} -->`] : []),
  ].join('\n\n') + '\n' };
}
